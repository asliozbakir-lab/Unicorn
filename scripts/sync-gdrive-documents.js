async function main() {
  console.log("Replacing documents with fully organized categorized Google Drive files...");
  await prisma.document.deleteMany();

  for (const doc of gdriveDocs) {
    await prisma.document.create({
      data: doc,
    });
  }

  console.log(`Successfully synced ${gdriveDocs.length} categorized documents!`);
}

